class TempleFairManager {
  constructor() {
    this.totalKarma = 100;
  }

  // Draw a random Siam Si prediction
  shakeSiamSi() {
    const randomPick = SIAM_SI_PREDICTIONS[Math.floor(Math.random() * SIAM_SI_PREDICTIONS.length)];
    return randomPick;
  }

  // Pluck a lucky star
  pluckStar() {
    const reward = LUCKY_STAR_REWARDS[Math.floor(Math.random() * LUCKY_STAR_REWARDS.length)];
    this.totalKarma += 20;
    return {
      reward,
      totalKarma: this.totalKarma
    };
  }

  // Taste food
  tasteFood(foodId) {
    const item = TEMPLE_FOOD_STALLS.find(f => f.id === foodId);
    if (item) {
      this.totalKarma += 10;
      return {
        item,
        totalKarma: this.totalKarma
      };
    }
    return null;
  }
}

// Global Temple Fair Instance
window.templeFairManager = new TempleFairManager();
